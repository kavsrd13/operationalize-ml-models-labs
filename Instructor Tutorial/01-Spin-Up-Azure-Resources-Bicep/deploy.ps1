[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [string]$SubscriptionId,

    [Parameter(Mandatory = $false)]
    [string]$ResourceGroupName = "rg-diabetes-instructor",

    [Parameter(Mandatory = $false)]
    [string]$Location = "eastus",

    [Parameter(Mandatory = $false)]
    [string]$NamePrefix = "diabinst01"
)

$ErrorActionPreference = "Stop"

$templateFile = Join-Path $PSScriptRoot "main.bicep"
$tutorialRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
$envFile = Join-Path $tutorialRoot "tutorial.env"

if ($SubscriptionId) {
    Write-Host "Setting Azure subscription to: $SubscriptionId"
    az account set --subscription $SubscriptionId | Out-Null
}

$activeSubscription = az account show --query id -o tsv
if (-not $activeSubscription) {
    throw "Unable to read active Azure subscription. Run 'az login' first."
}

Write-Host "Creating resource group '$ResourceGroupName' in '$Location'..."
az group create `
    --name $ResourceGroupName `
    --location $Location `
    --output none

Write-Host "Deploying Bicep template..."
$outputs = az deployment group create `
    --resource-group $ResourceGroupName `
    --template-file $templateFile `
    --parameters location=$Location namePrefix=$NamePrefix `
    --query properties.outputs `
    -o json | ConvertFrom-Json

$workspaceName = $outputs.workspaceName.value
$storageAccountName = $outputs.storageAccountName.value
$keyVaultName = $outputs.keyVaultName.value
$containerRegistryName = $outputs.containerRegistryName.value
$applicationInsightsName = $outputs.applicationInsightsName.value

@(
    "# Generated by 01-Spin-Up-Azure-Resources-Bicep/deploy.ps1"
    "AZURE_SUBSCRIPTION_ID=$activeSubscription"
    "AZURE_RESOURCE_GROUP=$ResourceGroupName"
    "AZURE_LOCATION=$Location"
    "AZURE_WORKSPACE_NAME=$workspaceName"
    "AZURE_STORAGE_ACCOUNT=$storageAccountName"
    "AZURE_KEY_VAULT=$keyVaultName"
    "AZURE_CONTAINER_REGISTRY=$containerRegistryName"
    "AZURE_APP_INSIGHTS=$applicationInsightsName"
) | Set-Content -Path $envFile -Encoding UTF8

Write-Host ""
Write-Host "Deployment complete."
Write-Host "Workspace: $workspaceName"
Write-Host "Environment file: $envFile"
